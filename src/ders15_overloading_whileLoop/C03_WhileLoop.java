package ders15_overloading_whileLoop;

public class C03_WhileLoop {
    static void main() {

        //2 basamaklı sayıları aralarında bir boşluk olacak şekilde yanyana yazdırın

        for (int i = 10; i<=99; i++){
            System.out.print(i +" ");

        }

        //while loop ile yaparsak
        System.out.println("");

        int a =10;
        while (a<100) {
            System.out.print(a+" ");
            a++;
        }



    }
}
