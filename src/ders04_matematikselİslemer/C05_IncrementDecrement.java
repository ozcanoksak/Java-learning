package ders04_matematikselİslemer;

public class C05_IncrementDecrement {
    public static void main(String[] args) {

        int sayi=10;

        // bu sayıyı 3 artıralım ve yazıralım

        sayi = sayi + 3;
        System.out.println(sayi); //13

        sayi += 3;
        System.out.println(sayi); //16



        int sayi2=10;

        // bu sayıyı 1 arttırın

        sayi2 = sayi2 + 1;
        System.out.println(sayi2); //11

        sayi2 += 1;
        System.out.println(sayi2); //12

        sayi2 ++;
        System.out.println(sayi2); //13

        ++sayi2;
        System.out.println(sayi2); //14


        int sayi3=10;

        // bu sayıyı 1 eksiltin

        sayi3= sayi3 - 1;
        System.out.println(sayi3); //9

        sayi3 -= 1;
        System.out.println(sayi3); //8

        sayi3 --;
        System.out.println(sayi3); //7

        --sayi3;
        System.out.println(sayi3); //6





    }
}
