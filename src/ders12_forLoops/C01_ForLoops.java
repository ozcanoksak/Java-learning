package ders12_forLoops;

public class C01_ForLoops {
    static void main() {

        // 10 kere Java yazdırın

        String str= "Java\n";
        System.out.println(str.repeat(10));

        System.out.println(" ");

        //bunu for döngüsü ile daha kolay yapabiliriz

        for (int i = 0; i <=10 ; i++) {
            System.out.println("Java");

        }





    }
}
